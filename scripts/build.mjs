import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const src=f=>readFileSync(new URL('../'+f,import.meta.url),'utf8');
const data=JSON.parse(src('content/google-ai-courses.json'));
let html=src('src/html.mjs').replace(/\bexport\s+(?=const|function)/g,'');
let catalog=`const catalog=Object.freeze(${JSON.stringify([data])});\nconst categories=Object.freeze(['All','Scholarships','Internships','Competitions','Exchange Programs','Grants','Online Courses','AI Tools']);\n`+
 src('src/catalog.mjs').split('export function').slice(1).map(s=>'function'+s).join('');
let app=src('src/app.mjs').replace(/^import .*;\n/gm,'').replace(/const css = readFileSync\([^\n]+\n/,`const css=${JSON.stringify(src('public/app.css'))};\n`).replace(/const js = readFileSync\([^\n]+\n/,`const js=${JSON.stringify(src('public/app.js'))};\n`);
// The built Worker uses neither node:fs nor external runtime dependencies.
const worker=`// Generated by scripts/build.mjs; edit sources in src/ and public/ instead.\n${html}\n${catalog}\n${app}`;
mkdirSync(new URL('../dist/',import.meta.url),{recursive:true});
writeFileSync(new URL('../dist/worker.mjs',import.meta.url),worker);
console.log(`Built dist/worker.mjs (${Buffer.byteLength(worker)} bytes)`);
